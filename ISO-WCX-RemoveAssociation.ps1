# Remove a selected ISO-WCX WCX association from Total Commander without
# touching toolbar buttons, custom commands, or unrelated plugin handlers.
# DRY RUN by default. Use -Apply only with every TC window closed.
# Example:
# .\ISO-WCX-RemoveAssociation.ps1 -IniPath 'C:\TC\wincmd.ini' -Extension iso
# .\ISO-WCX-RemoveAssociation.ps1 -IniPath 'C:\TC\wincmd.ini' -Extension iso -Apply
[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$IniPath,
    [ValidatePattern('^[A-Za-z0-9+_.-]{1,20}$')][string]$Extension='iso',
    [string]$PluginPath,
    [switch]$Apply
)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'

function Same-Path([string]$A,[string]$B) {
    $aName=($A.Trim().Trim('"') -replace '/','\').TrimEnd('\')
    $bName=($B.Trim().Trim('"') -replace '/','\').TrimEnd('\')
    return [string]::Equals($aName,$bName,[StringComparison]::OrdinalIgnoreCase)
}
function Is-IsoWcx([string]$Value) {
    $parsed=[regex]::Match($Value,'^\s*\d+\s*,\s*(?<path>.+?)\s*$')
    if(-not $parsed.Success) { return $false }
    $file=$parsed.Groups['path'].Value.Trim().Trim('"')
    if($PluginPath) { return Same-Path $file $PluginPath }
    return [regex]::IsMatch($file, '(?i)(^|[\\/])ISO-WCX[\\/]ISO-WCX\.wcx$')
}

$ini=(Resolve-Path -LiteralPath $IniPath -ErrorAction Stop).ProviderPath
$metadata=Get-Item -LiteralPath $ini -ErrorAction Stop
if(($metadata.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
    throw 'Refusing to alter a symlink/reparse-point wincmd.ini.'
}
if($metadata.Length -gt 16MB) { throw 'Refusing oversized Total Commander INI.' }
$bytes=[IO.File]::ReadAllBytes($ini)
$start=0
$encoding=[Text.Encoding]::Default
if($bytes.Length -ge 3 -and $bytes[0] -eq 239 -and $bytes[1] -eq 187 -and $bytes[2] -eq 191) {
    $encoding=[Text.UTF8Encoding]::new($true,$true); $start=3
} elseif($bytes.Length -ge 2 -and $bytes[0] -eq 255 -and $bytes[1] -eq 254) {
    $encoding=[Text.UnicodeEncoding]::new($false,$true,$true); $start=2
} elseif($bytes.Length -ge 2 -and $bytes[0] -eq 254 -and $bytes[1] -eq 255) {
    $encoding=[Text.UnicodeEncoding]::new($true,$true,$true); $start=2
}
$text=$encoding.GetString($bytes,$start,$bytes.Length-$start)
if($text.IndexOf([char]0) -ge 0) { throw 'INI contains NUL bytes; refusing update.' }
# Refuse encodings which cannot be decoded/re-encoded byte-identically.
# This is essential for users with Russian/Hebrew buttons and custom menus.
$roundtrip=$encoding.GetBytes($text)
if($roundtrip.Length -ne ($bytes.Length-$start)) {
    throw 'INI encoding cannot be round-tripped losslessly.'
}
for($offset=0;$offset -lt $roundtrip.Length;$offset++) {
    if($roundtrip[$offset] -ne $bytes[$start+$offset]) {
        throw 'INI encoding round-trip changed bytes; refusing modification.'
    }
}
$lines=[regex]::Split($text,'(?<=\n)')
$active=''
$selected=New-Object 'System.Collections.Generic.List[int]'
$unrelated=New-Object 'System.Collections.Generic.List[int]'
$derived=New-Object 'System.Collections.Generic.List[int]'
for($i=0;$i -lt $lines.Length;$i++) {
    $line=([string]$lines[$i]).TrimEnd([char[]]@([char]13,[char]10))
    $sec=[regex]::Match($line,'^\s*\[\s*(?<section>[^\]]+?)\s*\]\s*$')
    if($sec.Success) {
        $active=$sec.Groups['section'].Value
        continue
    }
    if($active -ieq 'PackerPlugins64' -and
       $line -match '^\s*\$checksum\$\s*=') {
        $derived.Add($i)
    }
    if($active -ine 'PackerPlugins') {continue}
    $match=[regex]::Match($line,'^\s*(?<key>[^=\s]+)\s*=\s*(?<value>.*)$')
    if(-not $match.Success) { continue }
    if($match.Groups['key'].Value -ine $Extension) { continue }
    if(Is-IsoWcx $match.Groups['value'].Value) { $selected.Add($i) }
    else { $unrelated.Add($i) }
}
if($unrelated.Count -gt 0) {
    throw "Extension '$Extension' also has a different handler. Refusing ambiguous deletion."
}
Write-Host "INI: $ini"
Write-Host "Extension: $Extension"
Write-Host "Matching ISO-WCX entries: $($selected.Count)"
if($selected.Count -eq 0) {
    Write-Host 'No matching ISO-WCX association to remove. Nothing changed.'
    return
}
if(-not $Apply) {
    Write-Host 'DRY RUN: no files changed. Close Total Commander and repeat with -Apply.'
    return
}
if(@(Get-Process -Name 'TOTALCMD','TOTALCMD64' -ErrorAction SilentlyContinue).Count -gt 0) {
    throw 'Close all Total Commander windows before changing its configuration.'
}
$omit=New-Object 'System.Collections.Generic.HashSet[int]'
foreach($id in $selected) { [void]$omit.Add($id) }
# Only the autogenerated checksum is invalidated so TC recalculates its
# 64-bit plugin association cache on next launch. Other cache rows remain.
foreach($id in $derived) { [void]$omit.Add($id) }
$updated=New-Object System.Text.StringBuilder
for($i=0;$i -lt $lines.Length;$i++) {
    if(-not $omit.Contains($i)) { [void]$updated.Append([string]$lines[$i]) }
}
$backup="$ini.isowcx-association-backup-$(Get-Date -Format 'yyyyMMdd_HHmmss_fff')"
$tmp="$ini.isowcx-association-pending-$([guid]::NewGuid().ToString('N'))"
try {
    $payload=$encoding.GetBytes($updated.ToString())
    $bom=$encoding.GetPreamble()
    $output=[byte[]]::new($bom.Length+$payload.Length)
    [Array]::Copy($bom,0,$output,0,$bom.Length)
    [Array]::Copy($payload,0,$output,$bom.Length,$payload.Length)
    [IO.File]::WriteAllBytes($tmp,$output)
    [IO.File]::Replace($tmp,$ini,$backup)
} finally {
    if(Test-Path -LiteralPath $tmp) {
        Remove-Item -LiteralPath $tmp -Force
    }
}
Write-Host "SUCCESS: removed $($selected.Count) matching extension association(s)."
Write-Host "Backup: $backup"
Write-Host 'Reopen Total Commander to reload [PackerPlugins].'
